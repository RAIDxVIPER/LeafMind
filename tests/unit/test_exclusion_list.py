"""
tests/unit/test_exclusion_list.py
==================================
Tests for config/exclusion_list.json generated by scripts/build_exclusion_list.py.

Definition of Done (spec §6d-viii C1):
  - Hash count >= 2,075 (the DoD gate)
  - A sample of random hashes are actually present
  - No D2_Train hashes appear in the exclusion list (R13: D1 hashes only)

Usage:
  pytest tests/unit/test_exclusion_list.py -v

  For the D2_Train negative check (slow, reads ~27K files), run with:
  pytest tests/unit/test_exclusion_list.py -v -m "not slow"
  or include slow tests:
  pytest tests/unit/test_exclusion_list.py -v  (will skip if Dataset_2/ not present)

IMPORTANT (R13): The exclusion list contains D1 MD5s — files that should be EXCLUDED
from D2_Test_OOD evaluation, NOT files to exclude from training.
"""

import hashlib

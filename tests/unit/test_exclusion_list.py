# ── Core DoD Tests ──────────────────────────────────────────────────────────────

class TestExclusionListStructure:
    """Test that the exclusion_list.json has the correct structure and metadata."""

    def test_file_exists(self):
        assert EXCLUSION_LIST_PATH.exists(), (
            "config/exclusion_list.json must exist. "
            "Run: python scripts/build_exclusion_list.py"
        )

    def test_required_top_level_keys(self, exclusion_data):
        assert "_meta" in exclusion_data, "Missing '_meta' key"
        assert "excluded_md5s" in exclusion_data, "Missing 'excluded_md5s' key"
        assert "records" in exclusion_data, "Missing 'records' key"

    def test_meta_has_required_fields(self, exclusion_data):
        meta = exclusion_data["_meta"]
        required = [
            "excluded_hashes_total",
            "excluded_overlap_with_ood",
            "excluded_overlap_with_few_shot",
            "dod_gate_min",
            "dod_gate_passed",
        ]
        for field in required:
            assert field in meta, f"Missing meta field: {field}"

    def test_excluded_md5s_is_list(self, exclusion_data):
        assert isinstance(exclusion_data["excluded_md5s"], list)

    def test_records_is_list(self, exclusion_data):
        assert isinstance(exclusion_data["records"], list)

    def test_records_match_excluded_md5s_count(self, exclusion_data):
        assert len(exclusion_data["records"]) == len(exclusion_data["excluded_md5s"]), (
            "records and excluded_md5s must have the same length"
        )

    def test_record_structure(self, exclusion_data):
        """Spot-check the first 5 records for required fields."""
        for record in exclusion_data["records"][:5]:
            assert "md5" in record
            assert "d1_paths" in record
            assert "d2_ood_paths" in record
            assert "d2_few_shot_paths" in record
            assert "in_ood" in record
            assert "in_few_shot" in record
            # Each record must appear in at least one D2 split
            assert record["in_ood"] or record["in_few_shot"], (
                f"Record {record['md5']} appears in neither OOD nor FewShot — should not be excluded"
            )

    def test_md5s_are_valid_hex(self, excluded_md5_set):
        """All hashes must be valid 32-character hex strings."""
        for md5 in list(excluded_md5_set)[:100]:  # Check first 100
            assert len(md5) == 32, f"Invalid MD5 length: {md5!r}"
            assert all(c in "0123456789abcdef" for c in md5), f"Invalid MD5 hex: {md5!r}"


# ── DoD Gate Tests ──────────────────────────────────────────────────────────────

class TestExclusionListDoD:
    """Tests that directly verify the C1 Definition of Done from spec §6d-viii."""

    def test_hash_count_meets_dod_gate(self, excluded_md5_set):
        """
        DoD (spec §6d-viii C1): hash count >= 2,075.
        The actual expected value is 2,349 (2,085 D1<->OOD + 264 D1<->FewShot).
        The gate of 2,075 is the minimum required by the spec.
        """
        DOD_MINIMUM = 2075
        count = len(excluded_md5_set)
        assert count >= DOD_MINIMUM, (
            f"FAIL: exclusion list has {count} hashes, "
            f"but DoD requires >= {DOD_MINIMUM}. "
            "Re-run: python scripts/build_exclusion_list.py"
        )

    def test_dod_gate_flag_set_in_meta(self, exclusion_data):
        """The script must self-report dod_gate_passed=True."""
        assert exclusion_data["_meta"]["dod_gate_passed"] is True, (
            "dod_gate_passed=False in meta. Script detected a DoD failure."
        )

    def test_ood_overlap_matches_audit(self, exclusion_data):
        """
        D1<->D2_OOD overlap expected ~2,085 (audit: 1972 train + 103 val).
        Allow ±50 tolerance for rounding differences between audit methods.
        """
        ood_overlap = exclusion_data["_meta"]["excluded_overlap_with_ood"]
        assert abs(ood_overlap - 2085) <= 50, (
            f"D1<->OOD overlap = {ood_overlap}, expected ~2085 (tolerance ±50). "
            "Significant deviation from Part 1 audit — investigate."
        )

    def test_few_shot_overlap_matches_audit(self, exclusion_data):
        """
        D1<->D2_FewShot overlap expected ~263 (audit: 238 train + 25 val).
        Allow ±20 tolerance.
        """
        fs_overlap = exclusion_data["_meta"]["excluded_overlap_with_few_shot"]
        assert abs(fs_overlap - 263) <= 20, (
            f"D1<->FewShot overlap = {fs_overlap}, expected ~263 (tolerance ±20). "
            "Check audit numbers in dataset_audit.md."
        )

    def test_ood_contamination_rate_high(self, exclusion_data):
        """
        From the audit: D2_Test_OOD contamination is ~87.8% (I4).
        Measured: 88.0%. This confirms the critical contamination issue.
        """
        pct = exclusion_data["_meta"]["d2_ood_contamination_pct"]
        assert pct >= 80.0, (
            f"OOD contamination rate is {pct}%, expected >= 80%. "
            "Something is wrong with the exclusion computation."
        )


# ── Sample Hash Presence Tests ──────────────────────────────────────────────────

class TestRandomSamplePresence:
    """
    DoD (spec §6d-viii C1): verify a sample of 10 random hashes are present.
    These tests read from the records to pick 10 random D1 files and verify
    their MD5s are in the excluded set.
    """

    def test_10_random_hashes_present(self, exclusion_data, excluded_md5_set):
        """Pick 10 random records and verify their MD5s are in excluded_md5s."""
        records = exclusion_data["records"]
        sample_size = min(10, len(records))
        sample = random.sample(records, sample_size)
        for record in sample:
            assert record["md5"] in excluded_md5_set, (
                f"Record MD5 {record['md5']} is in records but not in excluded_md5s. "
                "Data integrity error in exclusion_list.json."
            )

    def test_no_duplicate_md5s_in_excluded_list(self, exclusion_data):
        """excluded_md5s must have no duplicates."""
        md5_list = exclusion_data["excluded_md5s"]
        assert len(md5_list) == len(set(md5_list)), (
            f"excluded_md5s contains duplicates! "
            f"List has {len(md5_list)} entries but only {len(set(md5_list))} unique."
        )

    @pytest.mark.skipif(not D1_ROOT.exists(), reason="Dataset/ not available in this environment")
    def test_sample_d1_files_hash_correctly(self, exclusion_data, excluded_md5_set):
        """
        Pick 3 random records with D1 paths, re-hash the actual files,
        and verify the stored MD5 matches the file content.
        This validates the hash computation is correct.
        """
        records_with_d1 = [r for r in exclusion_data["records"] if r["d1_paths"]]
        sample = random.sample(records_with_d1, min(3, len(records_with_d1)))
        for record in sample:
            d1_rel_path = record["d1_paths"][0]  # e.g. "images/train/train_00001.jpg"
            d1_full = D1_ROOT.parent / d1_rel_path
            if not d1_full.exists():
                pytest.skip(f"D1 file not found: {d1_full}")
            computed_md5 = md5_of_file(d1_full)
            assert computed_md5 == record["md5"], (
                f"MD5 mismatch for {d1_rel_path}: "
                f"stored={record['md5']}, computed={computed_md5}"
            )


# ── Negative: D2_Train Hashes Must NOT Appear ────────────────────────────────────

class TestD2TrainNotInExclusionList:
    """
    DoD (spec §6d-viii C1): verify no D2_Train hashes are in the exclusion list.
    R13: D1 images only in exclusion list; D2_Train is for classifier training.

    The fast version samples 50 random D2_Train files.
    The slow version checks ALL D2_Train files.
    """

    @pytest.mark.skipif(not (D2_ROOT / "Train").exists(), reason="Dataset_2/ not available")
    def test_sample_d2_train_not_in_exclusion_list(self, excluded_md5_set):
        """
        Sample 50 random D2_Train images. None should be in the exclusion list.
        The exclusion list is D1-only; D2_Train is PlantVillage and has no D1 overlap
        (audit §D2: D2_Train/Val/Test_ID <-> D2_Test_OOD = 0 by source difference).
        """
        d2_train_dir = D2_ROOT / "Train"
        all_train_images = [
            p for p in d2_train_dir.rglob("*")
            if p.suffix.lower() in IMAGE_EXTENSIONS
        ]
        assert len(all_train_images) > 0, "No images found in D2_Train"

        sample_size = min(50, len(all_train_images))
        sample = random.sample(all_train_images, sample_size)
        violations = []
        for p in sample:
            md5 = md5_of_file(p)
            if md5 in excluded_md5_set:
                violations.append(str(p.relative_to(D2_ROOT)))
        assert len(violations) == 0, (
            f"R13 VIOLATION: {len(violations)} D2_Train files found in exclusion list!\n"
            f"Violating files: {violations}\n"
            "The exclusion list must contain only D1 hashes."
        )

    @pytest.mark.slow
    @pytest.mark.skipif(not (D2_ROOT / "Train").exists(), reason="Dataset_2/ not available")
    def test_all_d2_train_not_in_exclusion_list(self, excluded_md5_set):
        """
        SLOW: Hashes ALL D2_Train images (~27K files) and verifies none are in the
        exclusion list. Mark with -m slow to run.
        """
        d2_train_dir = D2_ROOT / "Train"
        all_train_images = [
            p for p in d2_train_dir.rglob("*")
            if p.suffix.lower() in IMAGE_EXTENSIONS
        ]
        violations = []
        for p in all_train_images:
            md5 = md5_of_file(p)
            if md5 in excluded_md5_set:
                violations.append(str(p.relative_to(D2_ROOT)))
        assert len(violations) == 0, (
            f"R13 VIOLATION: {len(violations)} D2_Train files found in exclusion list!\n"
            f"First 10 violating files: {violations[:10]}"
        )


